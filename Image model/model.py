def make_gradcam_heatmap(img_array, model, last_conv_layer_name="conv5_block3_out"):
    """
    Generates Grad-CAM heatmap for a single image.
    """
    # Grad-CAM model: input → last conv layer + model output
    grad_model = tf.keras.models.Model(
        inputs=model.input,
        outputs=[model.get_layer("resnet50").get_layer(last_conv_layer_name).output, model.output]
    )

    with tf.GradientTape() as tape:
        conv_outputs, predictions = grad_model(img_array)
        loss = predictions[:, 0]  # assuming label 0 = Fake

    grads = tape.gradient(loss, conv_outputs)
    pooled_grads = tf.reduce_mean(grads, axis=(0,1,2))

    conv_outputs = conv_outputs[0]
    heatmap = tf.reduce_sum(conv_outputs * pooled_grads, axis=-1)

    heatmap = tf.maximum(heatmap, 0)
    heatmap /= tf.reduce_max(heatmap) + 1e-8  # avoid division by zero
    return heatmap.numpy()

