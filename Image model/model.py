def generate_explainability_report(model, grad_model, img_path, class_names, output_dir="gradcam_reports"):
    """
    Generate Grad-CAM and explainability report for a single image.

    Args:
        model: Trained Keras model
        grad_model: Grad-CAM model (outputs last conv + predictions)
        img_path: Path to the input image
        class_names: List of class names (e.g., ["real", "fake"])
        output_dir: Directory to save the results
    """
    os.makedirs(output_dir, exist_ok=True)

    # 1️⃣ Load and preprocess the image
    img = cv2.imread(img_path)
    if img is None:
        raise ValueError(f"Image not found at {img_path}")
    img = cv2.resize(img, (224, 224))
    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    img_array = np.expand_dims(img_rgb, axis=0) / 255.0

    # 2️⃣ Predict
    preds = model.predict(img_array)
    pred_index = np.argmax(preds[0])
    pred_prob = preds[0][pred_index]
    pred_class = class_names[pred_index]

    # 3️⃣ Generate Grad-CAM
    def make_gradcam_heatmap(img_array, grad_model, class_index=None):
        with tf.GradientTape() as tape:
            conv_outputs, predictions = grad_model(img_array)
            if class_index is None:
                class_index = tf.argmax(predictions[0])
            loss = predictions[:, class_index]
        grads = tape.gradient(loss, conv_outputs)
        pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))
        conv_outputs = conv_outputs[0]
        heatmap = conv_outputs @ pooled_grads[..., tf.newaxis]
        heatmap = tf.squeeze(heatmap)
        heatmap = tf.maximum(heatmap, 0) / tf.math.reduce_max(heatmap)
        return heatmap.numpy()

