def make_gradcam_heatmap(img_array, model, last_conv_layer_name):
    # 1. Find the Backbone (The part that actually has conv5_block3_3_conv)
    backbone = None
    for layer in model.layers:
        if hasattr(layer, 'layers'):
            # Check if this layer contains our target conv layer
            try:
                layer.get_layer(last_conv_layer_name)
                backbone = layer
                break
            except:
                continue

    if backbone is None: backbone = model

    # 2. Create the Grad-Model specifically using the backbone's input/output
    grad_model = tf.keras.Model(
        inputs=[backbone.input],
        outputs=[backbone.get_layer(last_conv_layer_name).output, backbone.output]
    )

    # 3. Calculate gradients
    with tf.GradientTape() as tape:
        # We must pass the img_array through any layers BEFORE the backbone if they exist
        # Usually, in Sequential, img_array goes straight to the backbone
        conv_outputs, predictions = grad_model(img_array)

        # We use the prediction from the backbone directly
        # If backbone output is (1, 2048), we take the max of that
        # Or if it's already the final class, we use that.
        loss = tf.reduce_max(predictions, axis=-1)

    # 4. Extract gradients
    grads = tape.gradient(loss, conv_outputs)
    pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))

    # 5. Build Heatmap
    conv_outputs = conv_outputs[0]
    heatmap = conv_outputs @ pooled_grads[..., tf.newaxis]
    heatmap = tf.squeeze(heatmap)

    # 6. Normalize
    heatmap = tf.maximum(heatmap, 0) / (tf.reduce_max(heatmap) + 1e-10)
    return heatmap.numpy()

