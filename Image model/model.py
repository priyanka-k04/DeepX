import tensorflow as tf

def make_gradcam_heatmap(img_array, model, resnet, last_conv_layer_name):
    last_conv_layer = resnet.get_layer(last_conv_layer_name)

    # Create a model mapping input → conv outputs
    conv_model = tf.keras.Model(
        inputs=model.input,
        outputs=last_conv_layer.output
    )

    with tf.GradientTape() as tape:
        conv_outputs = conv_model(img_array)
        tape.watch(conv_outputs)

        predictions = model(img_array)
        loss = predictions[:, 0]   # binary classifier

    grads = tape.gradient(loss, conv_outputs)

    pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))
    conv_outputs = conv_outputs[0]

    heatmap = conv_outputs @ pooled_grads[..., tf.newaxis]
    heatmap = tf.squeeze(heatmap)

    heatmap = tf.maximum(heatmap, 0) / tf.math.reduce_max(heatmap)
    return heatmap.numpy(), predictions.numpy()[0][0]

