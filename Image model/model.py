def make_gradcam_heatmap(img_array, model, base_model, last_conv_layer_name):
    """
    img_array: (1,224,224,3) normalized
    model: full Sequential model
    base_model: ResNet50 inside the Sequential model
    last_conv_layer_name: e.g., 'conv5_block3_out'
    """

    # 1️⃣ Grad-CAM model: only inputs to base_model, outputs last conv layer
    grad_model = tf.keras.models.Model(
        inputs=base_model.input,  # ResNet50 input
        outputs=base_model.get_layer(last_conv_layer_name).output
    )

    # 2️⃣ Forward pass through base_model
    with tf.GradientTape() as tape:
        conv_outputs = grad_model(img_array)
        tape.watch(conv_outputs)

        # Pass through full model to get predictions
        preds = model(img_array)
        # Take probability of class 'Fake' (assume label 0)
        loss = preds[:, 0]

    # 3️⃣ Compute gradients
    grads = tape.gradient(loss, conv_outputs)
    pooled_grads = tf.reduce_mean(grads, axis=(0,1,2))

    # 4️⃣ Generate heatmap
    conv_outputs = conv_outputs[0]
    heatmap = tf.reduce_sum(conv_outputs * pooled_grads, axis=-1)

    heatmap = tf.maximum(heatmap, 0)
    heatmap /= tf.reduce_max(heatmap)

    return heatmap.numpy()

